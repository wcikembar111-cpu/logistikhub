    message TEXT NOT NULL,
    category VARCHAR(50) DEFAULT 'info', -- 'info', 'urgent', 'warning', 'announcement'
    device_info VARCHAR(100) DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

